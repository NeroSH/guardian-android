package com.shdev.guardian.feature.parent.impl

import android.graphics.Bitmap
import android.graphics.Color
import androidx.compose.foundation.Image
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.layout.ContentScale
import androidx.core.graphics.createBitmap
import androidx.core.graphics.set
import com.google.zxing.BarcodeFormat
import com.google.zxing.EncodeHintType
import com.google.zxing.qrcode.QRCodeWriter
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel

/** Encodes [content] into a QR [Bitmap]. Pure ZXing — no external service, works offline. */
fun encodeQr(content: String, sizePx: Int = 640): Bitmap {
    val hints = mapOf(
        EncodeHintType.ERROR_CORRECTION to ErrorCorrectionLevel.M,
        EncodeHintType.MARGIN to 1,
    )
    val matrix = QRCodeWriter().encode(content, BarcodeFormat.QR_CODE, sizePx, sizePx, hints)
    val bmp = createBitmap(sizePx, sizePx, Bitmap.Config.RGB_565)
    for (x in 0 until sizePx) {
        for (y in 0 until sizePx) {
            bmp[x, y] = if (matrix[x, y]) Color.BLACK else Color.WHITE
        }
    }
    return bmp
}

@Composable
fun QrImage(content: String, modifier: Modifier = Modifier, sizePx: Int = 640) {
    val bitmap = remember(content, sizePx) { encodeQr(content, sizePx) }
    Image(
        bitmap = bitmap.asImageBitmap(),
        contentDescription = "Pairing QR code",
        modifier = modifier,
        contentScale = ContentScale.Fit,
    )
}
