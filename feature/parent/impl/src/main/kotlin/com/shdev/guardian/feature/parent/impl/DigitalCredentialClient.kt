    /**
     * @param nonce the SERVER-issued challenge nonce. It is bound into the presentation's key-binding
     * JWT, which is how the server later detects a replay. Never pass a locally generated value.
     * @return the raw `DigitalCredential.credentialJson`, to be forwarded byte-for-byte to the
     * backend — re-serializing it would invalidate the signature.
     *
     * @throws androidx.credentials.exceptions.GetCredentialCancellationException if the user
     * dismisses the sheet, or no eligible credential exists on the device. Callers must treat that as
     * "user backed out", not as an error.
     */
    @OptIn(ExperimentalDigitalCredentialApi::class)
    @RequiresApi(Build.VERSION_CODES.P)
    suspend fun requestVerifiedEmail(activity: Activity, nonce: String): String {
        val requestJson = unformattedRequestJsonBytes.toString(Charsets.UTF_8)
            .replace("@nonce", nonce)

        val request = GetCredentialRequest(
            listOf(GetDigitalCredentialOption(requestJson = requestJson))
        )

        val credential = credentialManager.getCredential(activity, request).credential
        return when (credential) {
            is DigitalCredential -> credential.credentialJson
            else -> error("Unexpected credential type: ${credential::class.simpleName}")
        }
    }

    companion object {
        /**
         * Whether the verified-email path can be offered at all. GMS version is not checked here —
         * an out-of-date GMS surfaces as a cancellation at request time, which the caller already
         * treats as "fall back to the password form".
         */
        @get:ChecksSdkIntAtLeast(api = Build.VERSION_CODES.P)
        val isSupported: Boolean
            get() = Build.VERSION.SDK_INT >= Build.VERSION_CODES.P
    }
}
